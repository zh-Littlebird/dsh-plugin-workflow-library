const SECRET_PATTERNS = [
  { label: 'OpenAI 风格密钥', pattern: /\bsk-[A-Za-z0-9_-]{16,}\b/g },
  { label: 'GitHub 令牌', pattern: /\bgh[pousr]_[A-Za-z0-9]{20,}\b/g },
  { label: 'AWS Access Key', pattern: /\bAKIA[0-9A-Z]{16}\b/g },
  { label: '私钥内容', pattern: /-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----/g },
  { label: 'Bearer 令牌', pattern: /\bBearer\s+[A-Za-z0-9._~+/-]{20,}=*/g },
  { label: 'URL 内嵌账号密码', pattern: /:\/\/[^\s/:@]+:[^\s/@]+@/g },
  {
    label: '赋值式口令',
    pattern: /\b(?:password|passwd|pwd|secret|api[_-]?key|access[_-]?key)\s*[:=]\s*(?!["'`]?(?:<|xxx|\*\*\*|\$\{|process\.env|os\.environ|\$env:|env\.|getenv|%[A-Za-z_][A-Za-z0-9_]*%))[^\s"'`]{6,}/gi,
  },
]

function text(value) {
  return typeof value === 'string' ? value.trim() : ''
}

function oneLine(value) {
  return text(value).replace(/\s*\r?\n\s*/g, ' ')
}

function listOf(value) {
  if (!Array.isArray(value)) return []
  return value.map((item) => (typeof item === 'string' ? item.trim() : '')).filter((item) => item.length > 0)
}

function cap(value, limit, field, warnings) {
  if (value.length <= limit) return value
  warnings.push(`${field} 超过 ${limit} 字，已截断`)
  return value.slice(0, limit).trimEnd()
}

function normalizeInputs(raw) {
  if (!Array.isArray(raw)) return []
  return raw
    .map((item) => {
      if (item === null || typeof item !== 'object') return null
      const name = text(item.name)
      if (name.length === 0) return null
      return {
        name,
        description: text(item.description),
        required: item.required === true,
        example: text(item.example),
        default: text(item.default),
      }
    })
    .filter(Boolean)
    .slice(0, LIMITS.maxInputs)
}

function normalizeSteps(raw, warnings) {
  if (!Array.isArray(raw)) return []
  return raw
    .map((item, index) => {
      if (item === null || typeof item !== 'object') return null
      const action = text(item.action)
      if (action.length === 0) return null
      return {
        title: cap(text(item.title) || `步骤 ${index + 1}`, LIMITS.stepTitle, `steps[${index}].title`, warnings),
        action: cap(action, LIMITS.action, `steps[${index}].action`, warnings),
        how: cap(text(item.how), LIMITS.how, `steps[${index}].how`, warnings),
        tools: listOf(item.tools).slice(0, 10),
        expect: cap(text(item.expect), LIMITS.expect, `steps[${index}].expect`, warnings),
        onFailure: cap(text(item.onFailure), LIMITS.onFailure, `steps[${index}].onFailure`, warnings),
      }
    })
    .filter(Boolean)
}

function normalizeAssets(raw) {
  if (!Array.isArray(raw)) return []
  return raw
    .map((item) => {
      if (item === null || typeof item !== 'object') return null
      const file = text(item.path)
      const content = typeof item.content === 'string' ? item.content : ''
      if (file.length === 0 || content.length === 0) return null
      return { path: file, content }
    })
    .filter(Boolean)
    .slice(0, LIMITS.maxAssets)
}

/**
 * Coerce model input into the canonical draft shape.
 * @param {unknown} raw tool arguments
 * @returns {{ draft: object, warnings: string[], overwrite: boolean }}
 */
export function normalizeDraft(raw) {
  const input = raw !== null && typeof raw === 'object' ? raw : {}
  const warnings = []

  const draft = {
    name: text(input.name).toLowerCase(),
    title: cap(text(input.title) || text(input.name), LIMITS.title, 'title', warnings),
    description: cap(oneLine(input.description), LIMITS.description, 'description', warnings),
    whenToUse: cap(oneLine(input.whenToUse), LIMITS.whenToUse, 'whenToUse', warnings),
    tags: listOf(input.tags).slice(0, 12),
    inputs: normalizeInputs(input.inputs),
    preconditions: listOf(input.preconditions).slice(0, 20),
    steps: normalizeSteps(input.steps, warnings),
    validation: listOf(input.validation).slice(0, 20),
    pitfalls: listOf(input.pitfalls).slice(0, 20),
    artifacts: listOf(input.artifacts).slice(0, 20),
    references: listOf(input.references).slice(0, 30),
    assets: normalizeAssets(input.assets),
    notes: text(input.notes),
  }

  return { draft, warnings, overwrite: input.overwrite === true }
}

/**
 * Resolve the directory-safe relative path of an asset.
 * @param {string} value model-supplied relative path
 * @returns {string} normalized POSIX-style relative path
 */
export function safeAssetPath(value) {
  const normalized = String(value).replace(/\\/g, '/').trim()
  if (normalized.length === 0) throw new Error('assets 路径不能为空')
  if (normalized.startsWith('/') || /^[A-Za-z]:/.test(normalized)) throw new Error(`assets 路径必须是相对路径：${value}`)
  const parts = normalized.split('/')
  if (parts.some((part) => part === '' || part === '.' || part === '..')) {
    throw new Error(`assets 路径不能包含空段、. 或 ..：${value}`)
  }
  if (parts.some((part) => /[\u0000-\u001f<>:"|?*]/.test(part))) {
    throw new Error(`assets 路径包含非法字符：${value}`)
  }
  return parts.join('/')
}

function walkStrings(value, at, visit) {
  if (typeof value === 'string') {
    visit(value, at)
    return
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => walkStrings(item, `${at}[${index}]`, visit))
    return
  }
  if (value !== null && typeof value === 'object') {
    for (const [key, item] of Object.entries(value)) walkStrings(item, at === '' ? key : `${at}.${key}`, visit)
  }
}

/**
 * Report likely secrets so a workflow never stores a live credential.
 * @param {object} draft normalized draft
 * @returns {Array<{ path: string, label: string }>}
 */
export function scanSecrets(draft) {
  const findings = []
  walkStrings(draft, '', (value, at) => {
    for (const { label, pattern } of SECRET_PATTERNS) {
      pattern.lastIndex = 0
      if (pattern.test(value)) findings.push({ path: at, label })
    }
  })
  return findings
}

/**
 * Structural and safety checks that the JSON Schema cannot express.
 * @param {object} draft normalized draft
 * @param {{ knownTools?: Set<string> }} options
 * @returns {{ errors: string[], warnings: string[] }}
 */
export function findProblems(draft, options = {}) {
  const errors = []
  const warnings = []
  const knownTools = options.knownTools

  if (!NAME_PATTERN.test(draft.name)) {
    errors.push('name 必须是 2-64 位小写字母、数字或短横线，且以字母或数字开头结尾（例：deploy-gpustack-model）')
  } else if (RESERVED_NAMES.has(draft.name)) {
    errors.push(`name「${draft.name}」是保留名，请换一个`)
  }
  if (draft.title.length === 0) errors.push('title 不能为空')
  if (draft.description.length === 0) errors.push('description 不能为空：用一句话说明这个工作流做什么')
  if (draft.whenToUse.length === 0) errors.push('whenToUse 不能为空：说明什么情况下该用它')
  if (draft.steps.length < 2) errors.push('steps 至少 2 步：把流程拆成可执行的有序步骤')
  if (draft.validation.length < 1) errors.push('validation 至少 1 条：写清楚怎么算成功')

  draft.steps.forEach((step, index) => {
    if (step.title.length === 0) errors.push(`steps[${index}].title 不能为空`)
    if (step.tools.length > 0 && knownTools !== undefined) {
      const unknown = step.tools.filter((name) => !knownTools.has(name))
      if (unknown.length > 0) warnings.push(`steps[${index}] 引用了当前不可见的工具：${unknown.join('、')}`)
    }
  })

  for (const asset of draft.assets) {
    try {
      safeAssetPath(asset.path)
    } catch (error) {
      errors.push(error instanceof Error ? error.message : String(error))
    }
    const bytes = Buffer.byteLength(asset.content, 'utf8')
    if (bytes > LIMITS.assetBytes) errors.push(`assets「${asset.path}」超过 ${LIMITS.assetBytes / 1024}KB`)
  }
  const totalBytes = draft.assets.reduce((sum, asset) => sum + Buffer.byteLength(asset.content, 'utf8'), 0)
  if (totalBytes > LIMITS.totalAssetBytes) errors.push(`assets 总量超过 ${LIMITS.totalAssetBytes / 1024}KB`)

  for (const finding of scanSecrets(draft)) {
    errors.push(`${finding.path || '内容'} 疑似包含${finding.label}；请改成 <REDACTED> 占位，不要把真实密钥写进工作流`)
  }

  return { errors, warnings }
}

function detectLanguage(draft) {
  const sample = `${draft.title} ${draft.description} ${draft.steps[0]?.action ?? ''}`
  return /[\u4e00-\u9fff]/.test(sample) ? 'zh' : 'en'
}

function pickLanguage(language, draft) {
  if (language === 'zh' || language === 'en') return language
  return detectLanguage(draft)
}

function quote(value) {
  return JSON.stringify(value)
}

function tableCell(value, limit = 80) {
  const normalized = oneLine(value).replace(/\|/g, '\\|')
  return normalized.length > limit ? `${normalized.slice(0, limit)}…` : normalized
}

function fence(content) {
  const marker = content.includes('```') ? '````' : '```'
  return `${marker}text\n${content}\n${marker}`
}

function renderHow(how, t) {
  if (how.length === 0) return []
  if (!how.includes('\n') && !how.includes('`')) return [`- **${t.exec}**：\`${how}\``]
  return [`- **${t.exec}**：`, '', fence(how)]
}

/**
 * Render the model-facing SKILL.md body.
 * @param {object} draft normalized draft
 * @param {{ version: string, updatedAt: string, language?: 'auto'|'zh'|'en' }} meta
 * @returns {string}
 */
export function renderSkill(draft, meta) {
  const language = pickLanguage(meta.language ?? 'auto', draft)
  const t = TEXT[language]
  const lines = []

  lines.push('---')
  lines.push(`name: ${quote(draft.name)}`)
  lines.push(`description: ${quote(draft.description)}`)
  lines.push(`whenToUse: ${quote(draft.whenToUse)}`)
  lines.push('metadata:')
  lines.push(`  title: ${quote(draft.title)}`)
  lines.push(`  version: ${quote(meta.version)}`)
  lines.push('  workflow: true')
  if (draft.tags.length > 0) lines.push(`  tags: [${draft.tags.map(quote).join(', ')}]`)
  lines.push(`  updated: ${quote(meta.updatedAt)}`)
  lines.push('---')
  lines.push('')
  lines.push(`# ${draft.title}`)
  lines.push('')
  lines.push(draft.description)
  lines.push('')
  lines.push(`## ${t.when}`)
  lines.push('')
  lines.push(draft.whenToUse)
  lines.push('')

  if (draft.inputs.length > 0) {
    lines.push(`## ${t.inputs}`)
    lines.push('')
    lines.push(`| ${t.param} | ${t.required} | ${t.description} | ${t.example} |`)
    lines.push('| --- | --- | --- | --- |')
    for (const input of draft.inputs) {
      lines.push(
        `| \`${tableCell(input.name, 40)}\` | ${input.required ? t.yes : t.no} | ${tableCell(input.description)} | ${tableCell(input.example)} |`,
      )
    }
    lines.push('')
  }

  if (draft.preconditions.length > 0) {
    lines.push(`## ${t.preconditions}`)
    lines.push('')
    for (const item of draft.preconditions) lines.push(`- ${item}`)
    lines.push('')
  }

  lines.push(`## ${t.steps}`)
  lines.push('')
  draft.steps.forEach((step, index) => {
    lines.push(`### ${index + 1}. ${step.title}`)
    lines.push('')
    lines.push(step.action)
    lines.push('')
    const body = []
    body.push(...renderHow(step.how, t))
    if (step.expect.length > 0) body.push(`- **${t.expect}**：${step.expect}`)
    if (step.onFailure.length > 0) body.push(`- **${t.onFailure}**：${step.onFailure}`)
    if (step.tools.length > 0) body.push(`- **${t.tools}**：${step.tools.map((tool) => `\`${tool}\``).join('、')}`)
    if (body.length > 0) {
      lines.push(...body.filter((line, position) => !(line === '' && position === 0)))
      lines.push('')
    }
  })

  lines.push(`## ${t.validation}`)
  lines.push('')
  for (const item of draft.validation) lines.push(`- ${item}`)
  lines.push('')

  if (draft.pitfalls.length > 0) {
    lines.push(`## ${t.pitfalls}`)
    lines.push('')
    for (const item of draft.pitfalls) lines.push(`- ${item}`)
    lines.push('')
  }
  if (draft.artifacts.length > 0) {
    lines.push(`## ${t.artifacts}`)
    lines.push('')
    for (const item of draft.artifacts) lines.push(`- ${item}`)
    lines.push('')
  }
  if (draft.references.length > 0) {
    lines.push(`## ${t.references}`)
    lines.push('')
    for (const item of draft.references) lines.push(`- ${item}`)
    lines.push('')
  }
  if (draft.notes.length > 0) {
    lines.push(`## ${t.notes}`)
    lines.push('')
    lines.push(draft.notes)
    lines.push('')
  }

  lines.push('---')
  lines.push('')
  lines.push(`> ${t.generated} · ${meta.updatedAt.slice(0, 10)}`)
  lines.push('')
  return lines.join('\n')
}

/**
 * Render the human-facing INDEX.md for a whole library.
 * @param {Array<object>} entries entries returned by the store
 * @param {{ root: string, language?: 'auto'|'zh'|'en', generatedAt?: string }} meta
 * @returns {string}
 */
export function renderIndex(entries, meta) {
  const language = meta.language === 'zh' || meta.language === 'en'
    ? meta.language
    : entries.some((entry) => /[\u4e00-\u9fff]/.test(`${entry.title} ${entry.whenToUse}`))
      ? 'zh'
      : 'en'
  const t = TEXT[language]
  const generatedAt = meta.generatedAt ?? new Date().toISOString()
  const lines = [
    `# ${t.indexTitle}`,
    '',
    `- ${t.rootLabel}：\`${meta.root}\``,
    `- ${t.countLabel}：${entries.length}`,
    `- ${t.updatedLabel}：${generatedAt.slice(0, 10)}`,
    '',
    `| ${t.name} | ${t.title} | ${t.when} | ${t.stepsCount} | ${t.updatedLabel} |`,
    '| --- | --- | --- | --- | --- |',
  ]
  for (const entry of entries) {
    const relative = `${entry.name}/SKILL.md`
    lines.push(
      `| [\`${tableCell(entry.name, 48)}\`](./${relative}) | ${tableCell(entry.title)} | ${tableCell(entry.whenToUse ?? '')} | ${entry.steps ?? 0} | ${(entry.updatedAt ?? '').slice(0, 10)} |`,
    )
  }
  lines.push('')
  lines.push('---')
  lines.push('')
  lines.push(`> ${t.generated}`)
  lines.push('')
  return lines.join('\n')
}

/** Bump a semver-ish version; unparseable values restart at 1.0.1. */
export function bumpVersion(version) {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(version ?? ''))
  if (!match) return '1.0.1'
  return `${match[1]}.${match[2]}.${Number(match[3]) + 1}`
}

/** Absolute skill path for one workflow name. */
export function skillPathFor(root, name) {
  return path.join(root, name, 'SKILL.md')
}
