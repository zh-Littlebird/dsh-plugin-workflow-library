/**
 * Workflow document model for dsh-plugin-workflow-library.
 *
 * One workflow is a directory bundle that is also a DSH skill:
 *   <root>/<name>/SKILL.md      frontmatter + model-facing procedure
 *   <root>/<name>/workflow.json canonical structured record
 *   <root>/<name>/assets/...    optional scripts and templates
 *
 * `workflow.json` is authoritative; `SKILL.md` is rendered from it so the two
 * never drift at creation time. Nothing here touches the filesystem.
 */

import path from 'node:path'

/** `name` is the folder name and the skill name, so it must stay portable. */
export const NAME_PATTERN = /^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/

const RESERVED_NAMES = new Set(['index', 'assets', 'node_modules', 'tmp', 'trash', 'con'])

